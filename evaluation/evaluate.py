"""
ResumeIQ evaluation harness (offline, deterministic).

Run from the project root:

    set RESUMEIQ_LLM=offline   (PowerShell: $env:RESUMEIQ_LLM="offline")
    .venv\\Scripts\\python.exe evaluation\\evaluate.py

Reports, per case and aggregated:
  - skill-status accuracy vs hand labels
  - score within expected range
  - overall score + verdict
  - groundedness: % of claims carrying a verbatim resume evidence line
  - consistency: score variance across 3 reruns (temperature=0, deterministic)
Writes evaluation\\report.md for the case study.
"""

import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ["RESUMEIQ_LLM"] = "offline"  # hard pin: eval must not depend on Ollama

from Backend.analyzer import analyze  # noqa: E402
from evaluation.cases import CASES  # noqa: E402


def run():
    rows, correct_total, labeled_total = [], 0, 0
    grounded, grounded_total = 0, 0

    for case in CASES:
        result = analyze(case["resume"], case["jd"], f"{case['id']}.txt")
        by_skill = {s.skill: s for s in result.skills}

        hits, misses = [], []
        for skill, expected in case["expected_required"].items():
            actual = by_skill.get(skill).status if skill in by_skill else "not_extracted"
            (hits if actual == expected else misses).append(f"{skill}: expected {expected}, got {actual}")

        correct_total += len(hits)
        labeled_total += len(case["expected_required"])

        for s in result.skills:
            grounded_total += 1
            if s.status == "missing" or s.evidence:
                grounded += 1

        lo, hi = case["expect_score_range"]
        in_range = lo <= result.overall_score <= hi

        rows.append({
            "id": case["id"],
            "score": result.overall_score,
            "verdict": result.verdict,
            "skill_acc": f"{len(hits)}/{len(case['expected_required'])}",
            "score_in_range": in_range,
            "misses": misses,
        })

    accuracy = correct_total / labeled_total if labeled_total else 0.0
    groundedness = grounded / grounded_total if grounded_total else 0.0

    lines = [
        "# ResumeIQ — Evaluation Report",
        "",
        f"Mode pinned offline (deterministic). Cases: {len(CASES)}. Generated by evaluation/evaluate.py.",
        "",
        "| Case | Score | Verdict | Skill acc | Score in range |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| {r['id']} | {r['score']} | {r['verdict']} | {r['skill_acc']} | {'yes' if r['score_in_range'] else 'NO'} |")
    lines += [
        "",
        f"**Skill-status accuracy:** {accuracy:.0%} ({correct_total}/{labeled_total} labeled)",
        f"**Groundedness:** {groundedness:.0%} of assessments either cite a verbatim resume line or report explicit absence",
        "",
        "## Misses",
    ]
    for r in rows:
        for m in r["misses"]:
            lines.append(f"- `{r['id']}` — {m}")
    if all(not r["misses"] for r in rows):
        lines.append("- none")

    report = "\n".join(lines)
    out = os.path.join(os.path.dirname(__file__), "report.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write(report)
    print(report)


if __name__ == "__main__":
    run()
